/**
 * Add / expand flat dictionary lists in data/word-lists.json.
 * Run: node scripts/expand-dictionary-lists.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LISTS_FILE = path.join(ROOT, 'data', 'word-lists.json');
const WORDS_FILE = path.join(ROOT, 'data', 'words-merged.json');

const data = JSON.parse(fs.readFileSync(LISTS_FILE, 'utf8'));
const words = JSON.parse(fs.readFileSync(WORDS_FILE, 'utf8'));

const byName = {};
words.forEach(function (w) {
  byName[w.word.toLowerCase()] = w;
});

function wordEntries(names) {
  return names
    .filter(function (name) {
      return byName[name.toLowerCase()];
    })
    .map(function (name, i) {
      return { word: byName[name.toLowerCase()].word, index: i + 1 };
    });
}

function upsertList(spec) {
  var existing = data.lists.find(function (l) {
    return l.id === spec.id;
  });
  if (existing) {
    existing.title = spec.title;
    existing.listType = 'dictionary';
    existing.icon = spec.icon;
    existing.color = spec.color;
    existing.groups = [];
    existing.words = spec.words;
    console.log('Updated', spec.id, '→', spec.words.length, 'words');
    return;
  }
  data.lists.push({
    id: spec.id,
    listNum: data.lists.length + 1,
    title: spec.title,
    listType: 'dictionary',
    icon: spec.icon,
    color: spec.color,
    groups: [],
    words: spec.words,
  });
  console.log('Added', spec.id, '→', spec.words.length, 'words');
}

