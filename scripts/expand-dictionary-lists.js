var ieltsPick = words
  .filter(function (w) {
    return w.tags && w.tags.indexOf('IELTS') >= 0 && w.def && !/^Vocabulary word from List/i.test(w.def);
  })
  .slice(0, 40)
  .map(function (w) {
    return w.word;
  });

var academicPick = words
  .filter(function (w) {
    return w.def && w.syn && !w.stub;
  })
  .slice(0, 35)
  .map(function (w) {
    return w.word;
  });

